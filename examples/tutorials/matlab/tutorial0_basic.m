% R3XA Tutorial 0 - create and save a basic document from MATLAB.
here = fileparts(mfilename("fullpath"));
repo_root = fileparts(fileparts(fileparts(here)));
addpath(genpath(fullfile(repo_root, "matlab")));

artifact_dir = fullfile(repo_root, "artifacts", "examples", "tutorials");
if ~isfolder(artifact_dir)
    mkdir(artifact_dir);
end

document = r3xa.R3XAFile( ...
    "title", "R3XA MATLAB tutorial", ...
    "description", "Minimal document built with the MATLAB binding", ...
    "authors", {r3xa.author("R3XA API")}, ...
    "date", "2026-09-23" ...
);

light = document.add_generic_setting( ...
    "Spot light", ...
    "Illustrative illumination source", ...
    "documentation", "MULTILED_QX.pdf" ...
);

camera_title = "CCD Camera";
camera_description = "Illustrative camera";
camera_components = 1;
camera_dimension = "surface";
camera_units = {r3xa.unit("graylevel", 1.0, "gl", 1.0)};
camera_manufacturer = "Allied Vision Technologies";
camera_model = "Dolphin F-145B";
camera_image_size = { ...
    r3xa.unit("width", 1392, "px", 1.0), ...
    r3xa.unit("height", 1040, "px", 1.0) ...
};
camera = document.add_camera_source( ...
    camera_title, camera_description, camera_components, camera_dimension, ...
    camera_units, camera_manufacturer, camera_model, camera_image_size ...
);

document.add_list_data_set( ...
    "Visible images", ...
    {camera.id}, ...
    [0.0, 0.5, 1.0], ...
    {"img_0000.tif", "img_0001.tif", "img_0002.tif"}, ...
    "description", "Illustrative image sequence", ...
    "path", "images/" ...
);

document.save(fullfile(artifact_dir, "matlab_tutorial0_basic.json"));
disp("Saved MATLAB tutorial document. Validate the JSON with the Python API or WebUI.");
