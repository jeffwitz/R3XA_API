% R3XA large-rotation torsion case built with the MATLAB binding.
here = fileparts(mfilename("fullpath"));
repo_root = fileparts(fileparts(fileparts(here)));
addpath(genpath(fullfile(repo_root, "matlab")));

artifact_dir = fullfile(repo_root, "examples", "artifacts");
if ~isfolder(artifact_dir)
    mkdir(artifact_dir);
end

document = r3xa.R3XAFile( ...
    "title", "Large-Rotation Torsion Test on HMA Sample", ...
    "description", "Metadata for a large-rotation torsion test with mono-camera PhDIC", ...
    "authors", { ...
        r3xa.author("P. Avetisian", "Sorbonne Université"), ...
        r3xa.author("J. C. Passieux", "INSA-Toulouse - ICA", "https://orcid.org/0000-0001-8387-4122"), ...
        r3xa.author("J. N. Périé", "Toulouse University - ICA", "https://orcid.org/0000-0002-1522-3931") ...
    }, ...
    "date", "2025-07-02" ...
);

lights = document.add_generic_setting( ...
    "Spotlights", ...
    "Two indirect MultiLed QX spotlights", ...
    "documentation", "https://www.blinktech.com.au/wp-content/uploads/2023/10/MULTILED_QX.pdf" ...
);
machine = document.add_testing_machine_setting( ...
    "Torsion apparatus", ...
    "Andilog Twist torsion test stand", ...
    "electromechanical", ...
    "manufacturer", "Andilog", ...
    "model", "Drivetwist", ...
    "capacity", r3xa.unit("capacity", 40, "Nm", 1.0) ...
);
sample = document.add_specimen_setting( ...
    "Sample", ...
    "Hot-melt adhesive cylindrical specimen", ...
    "patterning_technique", "Matte black and white spray paint", ...
    "sizes", {r3xa.unit("diameter", 7, "mm", 1.0), r3xa.unit("length", 150, "mm", 1.0)} ...
);
calibration_board = document.add_generic_setting( ...
    "Calibration board", ...
    "Circles grid of 12 by 9 with 5 mm spacing", ...
    "grid", [12, 9], ...
    "spacing", r3xa.unit("spacing", 5, "mm", 1.0) ...
);

torque_sensor = document.add_generic_source( ...
    "Dynamic Torque sensor", ...
    "Andilog dynamic torque sensor", ...
    1, "point", {r3xa.unit("torque", 1, "Nm", 1.0)}, ...
    "Andilog", "SPIP TT 6", ...
    "capacity", r3xa.unit("capacity", 6, "Nm", 1.0), ...
    "uncertainty", r3xa.unit("uncertainty", 0.6, "mNm", 1.0) ...
);
angle_sensor = document.add_generic_source( ...
    "Dynamic Angle sensor", ...
    "Andilog dynamic angle sensor", ...
    1, "point", {r3xa.unit("angle", 1, "deg", 1.0)}, ...
    "Andilog", "Dynamic angle sensor", ...
    "uncertainty", r3xa.unit("uncertainty", 0.1, "deg", 1.0) ...
);
camera = document.add_camera_source( ...
    "CCD Camera", ...
    "Mono camera used for the torsion experiment", ...
    1, "surface", {r3xa.unit("graylevel", 1, "gl", 1.0)}, ...
    "Flir", "Grasshopper3 GS3-U3-51S5M", ...
    {r3xa.unit("width", 2048, "px", 1.0), r3xa.unit("height", 2048, "px", 1.0)}, ...
    "focal_length", r3xa.unit("focal_length", 50, "mm", 1.0), ...
    "exposure", r3xa.unit("exposure", 20, "ms", 1.0), ...
    "lens", "Tamron C-Mount 50mm f/2.8" ...
);
machine.attached_data_sources = {torque_sensor.id, angle_sensor.id};

t0 = r3xa.unit("time_reference", 0, "s", 1.0);
calibration_images = document.add_list_data_set( ...
    "Calibration images", {camera.id}, 72:96, ...
    arrayfun(@(i) sprintf("img1-%02d.png", i), 72:96, "UniformOutput", false), ...
    "description", "Images of the calibration grid", ...
    "path", "calib_img/", ...
    "data_type", "image/png", ...
    "time_reference", t0 ...
);
scanning_angles = document.add_file_data_set( ...
    "Scanning angles", {angle_sensor.id}, ...
    r3xa.data_set_file("resultats_angle_couple_rotation.csv", "file_type", "text/csv", "delimiter", ";", "col", "A", "rows", [1, 63]), ...
    r3xa.data_set_file("resultats_angle_couple_rotation.csv", "file_type", "text/csv", "delimiter", ";", "col", "C", "rows", [1, 63]), ...
    "description", "Rigid-body scanning angles", ...
    "time_reference", t0 ...
);
scanning_images = document.add_list_data_set( ...
    "Scanning images", {camera.id}, 0:61, ...
    arrayfun(@(i) sprintf("img0-%02d.png", i), 0:61, "UniformOutput", false), ...
    "description", "Images acquired during the rigid-body scan", ...
    "path", "rbm_img/", ...
    "data_type", "image/png", ...
    "time_reference", t0 ...
);

calibration_source = document.add_generic_source( ...
    "Camera Calibration", ...
    "OpenCV calibration using the calibration image dataset and target described in the settings", ...
    9, "point", { ...
        r3xa.unit("center x", 0, "px", 1.0), r3xa.unit("center y", 0, "px", 1.0), ...
        r3xa.unit("focal x", 0, "px", 1.0), r3xa.unit("focal y", 0, "px", 1.0) ...
    }, ...
    "Calibration tool", "OpenCV", ...
    "input_data_sets", {calibration_images.id} ...
);
intrinsics = document.add_generic_data_set( ...
    "Calibration parameters", {calibration_source.id}, "camera_intrinsics.txt", ...
    "description", "Intrinsic camera and distortion parameters" ...
);

document.settings = {machine, sample, calibration_board, lights};
document.data_sources = {torque_sensor, angle_sensor, camera, calibration_source};
document.data_sets = {scanning_angles, scanning_images, calibration_images, intrinsics};
document.save(fullfile(artifact_dir, "torsion_experiment_matlab.json"));
disp("Saved MATLAB torsion case. Validate the JSON with the Python API or WebUI.");
